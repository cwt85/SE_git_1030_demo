BEGIN;

CREATE TABLE events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    description TEXT,
    location VARCHAR(255),
    starts_at TIMESTAMPTZ,
    ends_at TIMESTAMPTZ,
    registration_deadline TIMESTAMPTZ,
    status VARCHAR(20) NOT NULL DEFAULT 'open',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_events_title CHECK (length(btrim(title)) > 0),
    CONSTRAINT ck_events_status CHECK (status IN ('open', 'closed', 'cancelled')),
    CONSTRAINT ck_events_times CHECK (ends_at IS NULL OR starts_at IS NULL OR ends_at >= starts_at)
);

CREATE TABLE registrations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_registrations_event FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE RESTRICT,
    CONSTRAINT uq_registrations_event_name_phone UNIQUE (event_id, name, phone),
    CONSTRAINT ck_registrations_name CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_registrations_phone CHECK (length(btrim(phone)) > 0)
);
CREATE INDEX ix_registrations_event_created ON registrations (event_id, created_at);

COMMIT;
